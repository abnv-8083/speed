ALTER TABLE invoice_items DISABLE ROW LEVEL SECURITY;
ALTER TABLE loans DISABLE ROW LEVEL SECURITY;
ALTER TABLE loan_payments DISABLE ROW LEVEL SECURITY;
ALTER TABLE cv_store DISABLE ROW LEVEL SECURITY;
ALTER TABLE vault_store DISABLE ROW LEVEL SECURITY;

-- 8. Create 'print_logs' table
CREATE TABLE IF NOT EXISTS print_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_name TEXT NOT NULL,
  paper_size TEXT NOT NULL CHECK (paper_size IN ('A4', 'A3', 'A5')),
  color_mode TEXT NOT NULL CHECK (color_mode IN ('Color', 'B&W')),
  quantity INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'Completed',
  source TEXT DEFAULT 'Manual Log',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE print_logs DISABLE ROW LEVEL SECURITY;
